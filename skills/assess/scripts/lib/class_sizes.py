"""File size per path class, so the L4 percentile reads production source alone (#820).

``loc_by_class`` takes ``(repository-relative path, lines)`` for every scored
file, sorts each into its ``lib.path_classes`` class and returns
``stats_summary.loc_by_class``: per class, ``files_scored`` and the ``p50``,
``p95`` and ``max`` of its line counts. A class with no file reads 0 files and
null percentiles, never 0 lines: unknown reads null. Layer 4 level 2 reads
``loc_by_class.source.p95``, so many small test fixtures cannot hide a large
source file and large tests cannot fail a repository whose source passes. The
test-set figure is ``loc_by_class.test``; every class's ``files_scored``
shows the denominator. The scored set has already lost vendored and
generated files to the scans' own excludes, so those two classes usually read
0 files.

Given the repository ``root``, ``loc_by_class`` also reads each file (#1419).
A file whose header marks it generated (``has_generated_header``: Pigeon's
"Autogenerated from Pigeon", a JNI generator's "DO NOT EDIT") is classed
``generated`` whatever its name, so a run with ``--include-artifacts`` keeps
it out of the source percentile and ``generated.files_scored`` counts it. An
Elixir file (``.ex``, ``.exs``) loses the non-blank lines of its
``@moduledoc``, ``@doc`` and ``@typedoc`` heredocs, opener and closer
included (``elixir_doc_lines``), so inline documentation does not count as
length; the code around them still counts. An unreadable file keeps its
name class and its line count. Without ``root`` the rows are used as given.

Both producers call it: the full run's sidecar (``complexity-treemap.py``
``write_stats``) and the headless block (``lib.run.headless_layers.stats_summary``).
``percentile`` is numpy's default (linear) rule, so the two agree. Tests:
``tests/test_class_sizes.py``.
"""
from __future__ import annotations

import re
from collections.abc import Iterable, Sequence
from pathlib import Path, PurePath

from lib.complexity.generated_files import has_generated_header
from lib.path_classes import PATH_CLASSES, PathClass, path_class
from lib.run_context_types_size import ClassLoc, LocByClass


def percentile(values: Sequence[float], q: float) -> float:
    """``numpy.percentile``'s default (linear) interpolation; 0.0 when empty."""
    ordered = sorted(values)
    if not ordered:
        return 0.0
    rank = (len(ordered) - 1) * q / 100.0
    low = int(rank)
    high = min(low + 1, len(ordered) - 1)
    return float(ordered[low] + (ordered[high] - ordered[low]) * (rank - low))


def class_loc(values: Sequence[float]) -> ClassLoc:
    """``files_scored`` and the distribution of ``values``; null percentiles when empty."""
    if not values:
        return {"files_scored": 0, "p50": None, "p95": None, "max": None}
    return {"files_scored": len(values), "p50": percentile(values, 50),
            "p95": percentile(values, 95), "max": float(max(values))}


ELIXIR_SUFFIXES = frozenset({".ex", ".exs"})

# `@moduledoc """`, `@doc ~S"""`, `@typedoc '''`: a doc attribute that opens a
# heredoc and holds nothing else on the line. `@doc false` and a one-line
# `@doc "..."` are left alone.
_ELIXIR_DOC_OPEN = re.compile(
    r"""^\s*@(?:moduledoc|doc|typedoc)\s*\(?\s*(?:~[sS])?("{3}|'{3})\s*$""")


def elixir_doc_lines(text: str) -> int:
    """Non-blank lines of the doc-attribute heredocs in Elixir ``text``,
    opener and closer included. An unclosed heredoc counts to the end."""
    count = 0
    closer: str | None = None
    for line in text.splitlines():
        if closer is not None:
            if line.strip():
                count += 1
            if line.lstrip().startswith(closer):
                closer = None
            continue
        m = _ELIXIR_DOC_OPEN.match(line)
        if m is not None:
            closer = m.group(1)
            count += 1
    return count


def _read_row(root: Path, rel: str | PurePath, lines: float) -> tuple[PathClass, float]:
    """The size class and the counted lines of one file read under ``root``."""
    path = root / rel
    if has_generated_header(path):
        return "generated", lines
    name_class = path_class(rel)
    if path.suffix.lower() not in ELIXIR_SUFFIXES:
        return name_class, lines
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return name_class, lines
    return name_class, max(0.0, lines - elixir_doc_lines(text))


def loc_by_class(rows: Iterable[tuple[str | PurePath, float]],
                 root: Path | None = None) -> LocByClass:
    """``stats_summary.loc_by_class`` from ``(relative path, lines)`` rows;
    with ``root``, read each file for a generated header and Elixir docs."""
    split: dict[PathClass, list[float]] = {name: [] for name in PATH_CLASSES}
    for rel, lines in rows:
        if root is None:
            split[path_class(rel)].append(float(lines))
            continue
        cls, counted = _read_row(root, rel, float(lines))
        split[cls].append(counted)
    return {
        "source": class_loc(split["source"]),
        "test": class_loc(split["test"]),
        "fixture": class_loc(split["fixture"]),
        "example": class_loc(split["example"]),
        "vendored": class_loc(split["vendored"]),
        "generated": class_loc(split["generated"]),
    }
