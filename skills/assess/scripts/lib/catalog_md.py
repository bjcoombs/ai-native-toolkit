"""``docs/what-we-measure.md``: the measures catalog (``lib.catalog``) as Markdown (#794).

``render_markdown(catalog)`` is pure and deterministic. It writes, in order: how grades
count, the conditions organised by truth tag (#870), how the tags relate (shared
conditions, Step gates, links), the maturity-model rows, each scan the headless runner
reports, the derived findings, and every registry scan.

A tag section is a ``### <tag title>`` heading, then the tag's opening lines
(``_tag_opening``), then one table of the conditions listed under that tag. Each condition
has one table row per criterion, under its first tag only, so it appears once however many
tags it carries; its other tags name it in an "Also carries this tag" line. The table's columns are
``CONDITION_COLUMNS``, one ``(header, cell)`` entry each; "Why it matters" holds the condition's
``why`` (#939). Links are
relative to ``docs/`` so they resolve in the repository. The words come from the check
manifest, so an edit there shows here once ``make catalog`` regenerates the file.

**Whys (#939).** A tag section's first line is the tag's ``why``; each scan section opens with
the scan's ``why``, or "Run plumbing" for a scan whose why is the ``exempt: plumbing`` token;
the finding table has a "Why it matters" column. A signal carries no why of its own, so every
section that names a signal path in backticks also holds the why of each condition the signal
feeds: ``_with_signal_whys`` adds a "Why the signals named here matter" list to any section that
lacks one of them. A version 1 manifest has no whys, and none of this is written.

"How the tags relate" holds the shared-condition matrix (``tag_pairs``; the diagonal is each
tag's own count), the Step gates table (the gates new at each Step, the conditions they
cover and their tags) and the requires, guard and equality links. A tag with no condition,
a model with no Steps, and no guard or equality link are each said in words.

**Generator and staleness test.** `scripts/gen_catalog.py` (`make catalog` from the repository
root) writes both files; `--check` writes nothing and exits 1 naming a stale one.
`tests/test_catalog.py::test_committed_catalog_is_current` fails when a committed copy differs,
so a PR that changes `core.toml`, a fragment under `checks/core/`, `default.toml` or `level_signals.py` regenerates the catalog.
`make check` runs it through `test-assess`.
"""
from __future__ import annotations

import json
import re
from collections.abc import Callable, Iterable
from typing import NamedTuple

from lib.catalog import UNCLASSIFIED, Catalog, CatalogCriterion, CatalogLevel, CatalogRow, CatalogScan
from lib.catalog_tags import CatalogTag, tag_title
from lib.manifest.manifest_whys import PLUMBING

PLUMBING_WORDS = "Run plumbing: no row or finding reads this scan."

HEADER = """# What /assess measures

<!-- Generated by skills/assess/scripts/gen_catalog.py (`make catalog`); do not edit by hand. -->

This page lists every check `/assess` and `/fleet` run, what each one reads, and how it
feeds the maturity model. It is generated from the check manifest
(`skills/assess/checks/core.toml`), the default maturity model
(`skills/assess/levels/default.toml`) and the signal input classes
(`skills/assess/scripts/lib/level_signals.py`), so it changes only when they do. The same
data for machines is [measures.json](../skills/assess/references/measures.json).

Nothing here is a judgement of a team. A gap is the next thing to try, and a check that
could not be read is shown as not measured with its reason: it earns nothing and costs
nothing.
"""

HEADLESS_WORDS = {
    "registered": "reported by headless and fleet runs",
    "headless_variant": "reported by headless and fleet runs (built by the headless runner's own scan)",
    "unregistered": "only a full /assess run builds it; headless and fleet runs report it not measured",
    "platform_only": "only with --platform; left out otherwise",
    "units_only": ("only with assess_signals --units (or --scans naming it) or fleet --monorepo-units; "
                   "left out otherwise"),
}


def _code(value: object) -> str:
    return f"`{value}`"


def _codes(values: Iterable[str]) -> str:
    """Backticked values joined by commas, or "-" when there are none."""
    return ", ".join(f"`{v}`" for v in values) or "-"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _grades(catalog: Catalog) -> list[str]:
    lines = ["## How evidence is graded", "",
             "Each signal has an input class: what its producer read. The class fixes a grade. "
             "Conditions graded measured or verified count toward a level; conditions graded "
             "config_only or declared are listed, not counted.", "",
             "| Grade | Input classes | Counts toward a level |", "|---|---|---|"]
    for g in catalog["grades"]:
        classes = ", ".join(_code(c) for c in g["input_classes"]) or "none"
        lines.append(f"| `{g['grade']}` | {classes} | {'yes' if g['counts'] else 'no, listed'} |")
    lines += ["", f"A scan that feeds no maturity-model criterion is `{UNCLASSIFIED}` until its "
              "evidence is classified (#789 step 6).", ""]
    return lines


class Line(NamedTuple):
    """One condition table row: a criterion of a condition (level) of a row."""

    row: CatalogRow
    level: CatalogLevel
    criterion: CatalogCriterion


def _condition_cell(line: Line) -> str:
    others = [tag_title(t) for t in line.level["truth"][1:]]
    shared = f" (shared with {', '.join(others)})" if others else ""
    return f"`{line.level['id']}` {_cell(line.criterion['title'])}{shared}"


def _criterion_cell(line: Line) -> str:
    c = line.criterion
    compared = c["eq_signal"] if c["eq_signal"] is not None else json.dumps(c["value"])
    return f"{_cell(c['text'])} (`{_cell(c['signal'] + ' ' + c['op'] + ' ' + compared)}`)"


def _links_cell(line: Line) -> str:
    level, parts = line.level, []
    parts += [f"requires `{r}`" for r in level["requires"]]
    if level["guarded_by"] is not None:
        parts.append(f"guarded by `{level['guarded_by']}`")
    if line.criterion["eq_signal"] is not None:
        parts.append(f"equals `{line.criterion['eq_signal']}`")
    return "; ".join(parts) or "-"


# The columns of a condition table, in order: (header, cell). A new column is one entry.
CONDITION_COLUMNS: tuple[tuple[str, Callable[[Line], str]], ...] = (
    ("Condition", _condition_cell),
    ("Producer", lambda line: f"`{line.criterion['producer']['scan']}`"),
    ("Criterion", _criterion_cell),
    # Grade and Counts are the whole condition's, as lib.level_tally scores it: its weakest signal.
    ("Grade", lambda line: f"`{line.level['grade']}`"),
    ("Counts", lambda line: "yes" if line.level["counts"] else "no, listed"),
    ("Step gate", lambda line: _codes(line.level["step_gates"])),
    ("Polarity", lambda line: line.level["polarity"]),
    ("Links", _links_cell),
    ("Why it matters", lambda line: _cell(line.criterion["why"]) or "-"),
    ("Next step", lambda line: _cell(line.criterion["fix"])),
)


def _table(lines: list[Line]) -> list[str]:
    out = ["| " + " | ".join(h for h, _ in CONDITION_COLUMNS) + " |",
           "|" + "---|" * len(CONDITION_COLUMNS)]
    out += ["| " + " | ".join(cell(line) for _, cell in CONDITION_COLUMNS) + " |" for line in lines]
    return out


def _lines(catalog: Catalog) -> dict[str, list[Line]]:
    """Each condition id to its table rows, in model order."""
    out: dict[str, list[Line]] = {}
    for row in catalog["rows"]:
        for level in row["levels"]:
            out[level["id"]] = [Line(row, level, c) for c in level["criteria"]]
    return out


def _tag_opening(tag: CatalogTag) -> list[str]:
    """The lines that open a tag section, before its table."""
    why = [tag["why"], ""] if tag["why"] else []
    total, shared = len(tag["conditions"]), len(tag["shared"])
    if not total:
        return [*why, f"Tag `{tag['id']}`. No condition carries this tag yet.", ""]
    noun = "condition" if total == 1 else "conditions"
    if not shared:
        share = "none shared with another tag"
    elif shared == total:
        share = "all shared with another tag" if total > 1 else "shared with another tag"
    else:
        share = f"{shared} shared with another tag"
    return [*why, f"Tag `{tag['id']}`: {total} {noun}, {share}.", ""]


def _tag_section(tag: CatalogTag, lines: dict[str, list[Line]], first: dict[str, str]) -> list[str]:
    out = [f"### {tag['title']}", "", *_tag_opening(tag)]
    rows = [line for cid in tag["listed"] for line in lines[cid]]
    if rows:
        out += [*_table(rows), ""]
    elsewhere = [cid for cid in tag["conditions"] if cid not in tag["listed"]]
    if elsewhere:
        out += ["Also carries this tag, listed under its first tag: "
                + ", ".join(f"`{cid}` ({tag_title(first[cid])})" for cid in elsewhere) + ".", ""]
    return out


def _by_tag(catalog: Catalog) -> list[str]:
    conditions = [lv for r in catalog["rows"] for lv in r["levels"]]
    multi = sum(len(lv["truth"]) > 1 for lv in conditions)
    out = ["## Conditions by truth tag", "",
           "Each condition carries one or more truth tags: the truth it keeps honest. A condition "
           "holds when all of its criteria hold, and each criterion's key is `<row>.<n>:<signal>`. "
           "A condition with several tags is listed under its first tag and named under the others "
           f"as shared; it counts once. There are {len(conditions)} conditions, {multi} of them "
           "with more than one tag.", "",
           "| Tag | Conditions | Listed here | Shared |", "|---|---|---|---|"]
    out += [f"| {t['title']} (`{t['id']}`) | {len(t['conditions'])} | {len(t['listed'])} | "
            f"{len(t['shared'])} |" for t in catalog["tags"]]
    out.append("")
    lines = _lines(catalog)
    first = {lv["id"]: lv["truth"][0] for lv in conditions if lv["truth"]}
    for tag in catalog["tags"]:
        out += _tag_section(tag, lines, first)
    return out


def _relations(catalog: Catalog) -> list[str]:
    ids = [t["id"] for t in catalog["tags"]]
    shared = {tuple(p["tags"]): len(p["conditions"]) for p in catalog["tag_pairs"]}
    own = {t["id"]: len(t["conditions"]) for t in catalog["tags"]}
    out = ["## How the tags relate", "", "### Shared conditions", "",
           "How many conditions each pair of tags shares. The diagonal is the tag's own count.", "",
           "| Tag | " + " | ".join(f"`{i}`" for i in ids) + " |", "|---|" + "---|" * len(ids)]
    for a in ids:
        cells = [str(own[a]) if a == b else str(shared.get((a, b), shared.get((b, a), 0))) for b in ids]
        out.append(f"| `{a}` | " + " | ".join(cells) + " |")
    out.append("")
    for pair in catalog["tag_pairs"]:
        out.append(f"- `{pair['tags'][0]}` and `{pair['tags'][1]}`: "
                   + ", ".join(f"`{c}`" for c in pair["conditions"]) + ".")
    if not catalog["tag_pairs"]:
        out.append("No two tags share a condition yet.")
    out += ["", "### Step gates", "",
            "The autonomy Steps in order. A Step needs every gate, whatever the gate's grade, and "
            "nothing else: no count of conditions moves a Step. Gates accumulate, so each Step keeps "
            "the gates below it.", "",
            "| Step | Name | New gates | Gate covers | Tags |", "|---|---|---|---|---|"]
    for step in catalog["steps"]:
        new = [g for g in step["gates"] if g["id"] in step["added_gates"]]
        out.append(f"| {step['step']} | {_cell(step['name'])} | "
                   f"{_codes(g['id'] for g in new)} | {_codes(c for g in new for c in g['conditions'])} | "
                   f"{_codes(t for g in new for t in g['tags'])} |")
    if not catalog["steps"]:
        out.append("| - | The model defines no Steps | - | - | - |")
    out += ["", "### Requires, guard and equality links", ""]
    words = {"requires": "requires", "guarded_by": "is guarded by", "eq_signal": "compares with signal"}
    out += [f"- `{link['source']}` {words[link['kind']]} `{link['target']}`." for link in catalog["links"]]
    kinds = {link["kind"] for link in catalog["links"]}
    absent = [none for kind, none in (("requires", "No condition requires another yet."),
                                      ("guarded_by", "No condition is guarded yet."),
                                      ("eq_signal", "No criterion compares two signals yet."))
              if kind not in kinds]
    if absent:
        out += ["", " ".join(absent)] if catalog["links"] else [" ".join(absent)]
    out.append("")
    return out


def _rows(catalog: Catalog) -> list[str]:
    lines = ["## Maturity-model rows", "",
             "The rows the conditions come from. A row's level is the highest level whose "
             "conditions, and every one below, hold.", "",
             "| Row | Title | Scope | Aggregated by | Levels |", "|---|---|---|---|---|"]
    for row in catalog["rows"]:
        lines.append(f"| `{row['id']}` | {_cell(row['title'])} | {row['scope']} | `{row['aggregation']}` | "
                     f"{_codes(lv['id'] for lv in row['levels'])} |")
    lines.append("")
    return lines


def _scan(scan: CatalogScan) -> list[str]:
    privacy = scan["privacy"]
    if not privacy["written"]:
        kept = "never written: an input to other scans"
    elif privacy["strings_kept"]:
        kept = ("numbers, booleans and nulls kept; strings by field: "
                + ", ".join(f"`{k}` {v}" for k, v in privacy["strings_kept"].items()))
    else:
        kept = "numbers, booleans and nulls kept; no string field kept"
    used = scan["used_by"]
    uses = [f"row {_code(r)}" for r in used["rows"]] + [f"finding {_code(f)}" for f in used["findings"]]
    if scan["evidence"]:
        evidence = ", ".join(f"`{e['signal']}` {e['input_class']} ({e['grade']})" for e in scan["evidence"])
    else:
        evidence = f"`{UNCLASSIFIED}`"
    lines = [f"### `{scan['name']}`: {scan['title']}", ""]
    if scan["why"]:
        lines += [PLUMBING_WORDS if scan["why"] == PLUMBING else scan["why"], ""]
    if scan["summary"]:
        lines += [scan["summary"], ""]
    network = "yes, GitHub or GitLab" + (" (with --platform)" if scan["platform"] else "") \
        if scan["network"] else "no"
    lines += [
        f"- Collector: `{scan['collector']}`, reading {', '.join(_code(r) for r in scan['reads']) or 'nothing'}.",
        f"- Network: {network}.",
        f"- Headless: {HEADLESS_WORDS[scan['headless']]}.",
        f"- Counts-only: {kept}.",
        f"- Used by: {', '.join(uses) or 'no row or finding yet'}.",
        f"- Evidence: {evidence}.",
    ]
    if scan["unknown_reasons"]:
        lines.append("- Not measured when:")
        lines += [f"  - `{r['code']}`: {r['means']} {r['next_step']}" for r in scan["unknown_reasons"]]
    else:
        lines.append("- Not measured when: it cannot read its input; the block says why.")
    lines.append("")
    return lines


def _findings(catalog: Catalog) -> list[str]:
    lines = ["## Derived findings", "", "In report order.", "",
             "| Finding | Reads | Why it matters | Next step | Mode | Rules |", "|---|---|---|---|---|---|"]
    for f in catalog["findings"]:
        rules = []
        if f["suppressed_when"]:
            rules.append(f"emptied when `{f['suppressed_when']}`")
        if f["prune_missing_paths"]:
            rules.append("deleted paths pruned")
        if not f["concern"]:
            rules.append("a strength, not a concern")
        lines.append(f"| `{f['name']}` {_cell(f['title'])} | {', '.join(_code(i) for i in f['inputs'])} | "
                     f"{_cell(f['why']) or '-'} | {_cell(f['action'])} | `{f['mode']}` | "
                     f"{_cell('; '.join(rules)) or '-'} |")
    lines.append("")
    return lines


def _collectors(catalog: Catalog) -> list[str]:
    lines = ["## Every registered scan", "",
             "The scan registry in run order, including the private inputs other scans read.", "",
             "| Scan | What it is | Reads | Writes | Network |", "|---|---|---|---|---|"]
    for c in catalog["collectors"]:
        writes = "private input" if c["private"] else ", ".join(_code(p) for p in c["publishes"])
        lines.append(f"| `{c['name']}` | {_cell(c['title'])} | "
                     f"{', '.join(_code(r) for r in c['reads']) or '-'} | {writes} | "
                     f"{'yes' if c['network'] else 'no'} |")
    lines.append("")
    return lines


_SPAN = re.compile(r"`([^`]+)`")
_TOKEN = re.compile(r"[a-z0-9_.]+")


def _feeds(catalog: Catalog) -> dict[str, list[tuple[str, str]]]:
    """Signal path -> ``(criterion key, why)`` of each condition criterion that reads it."""
    out: dict[str, list[tuple[str, str]]] = {}
    for row in catalog["rows"]:
        for level in row["levels"]:
            for c in level["criteria"]:
                if c["why"]:
                    out.setdefault(c["signal"], []).append((c["key"], c["why"]))
    return out


def _named(section: list[str]) -> set[str]:
    """Every dotted token inside a backticked span of the section."""
    return {t.strip(".") for line in section for span in _SPAN.findall(line) for t in _TOKEN.findall(span)}


def _with_signal_whys(lines: list[str], feeds: dict[str, list[tuple[str, str]]]) -> list[str]:
    """Each heading's section, plus the whys of the conditions fed by a signal it names that it
    does not hold yet."""
    sections: list[list[str]] = [[]]
    for line in lines:
        if line.startswith("#"):
            sections.append([])
        sections[-1].append(line)
    out: list[str] = []
    for section in sections:
        text, named = "\n".join(section), _named(section)
        extra: list[str] = []
        for signal, fed in feeds.items():
            if signal in named:
                extra += [f"- `{signal}` feeds `{key}`: {why}" for key, why in fed
                          if why not in text and why not in "\n".join(extra)]
        if extra:
            while section and not section[-1]:
                section.pop()
            section += ["", "Why the signals named here matter:", "", *extra, ""]
        out += section
    return out


def render_markdown(catalog: Catalog) -> str:
    """The catalog page, ending in one newline."""
    lines = [HEADER, *_grades(catalog), *_by_tag(catalog), *_relations(catalog), *_rows(catalog),
             "## Scans", "", "Every scan name `assess_signals.py --scans` accepts, in run order.", ""]
    for scan in catalog["scans"]:
        lines += _scan(scan)
    lines += [*_findings(catalog), *_collectors(catalog)]
    lines = _with_signal_whys("\n".join(lines).split("\n"), _feeds(catalog))
    return "\n".join(lines).rstrip("\n") + "\n"
