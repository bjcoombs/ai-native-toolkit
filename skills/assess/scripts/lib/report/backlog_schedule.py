"""The scheduled backlog reconcile (#814): one status comment per filed item, and the opt-in file and close modes.

The reconcile (``lib/report/backlog_reconcile.py``, #811) proposes on interactive runs only.
A daily workflow (``.github/workflows/reusable-backlog-reconcile.yml``) runs it with no one to
confirm, so this module turns its result into tracker writes bounded by ``.assess/config.toml``
``[backlog] mode`` (``assess_config.load_backlog_mode``):

- ``propose`` (default): the only write is the status line of each marked item's existing
  status comment. The proposals the interactive run would show go into that line, to be
  confirmed on the next interactive ``/assess``; nothing is closed, filed or commented.
- ``file``: as ``propose``, plus a status comment on a marked item that has none, plus one
  new item for each gate of the next Step (``level.next_step.blockers[].condition``) that no
  item is marked for, under the ``[backlog] wip`` limit, in condition id order, each with
  ``label`` so the next run's listing finds it.
- ``file-and-close``: as ``file``, plus closing an open marked item whose condition now holds
  (the reconcile's ``close`` proposal). A reopen, demote or supersede stays a proposal in
  every mode.

The **status comment** is one issue comment per item, found by ``STATUS_MARKER`` and written
by someone with write access (``authorAssociation`` ``OWNER``, ``MEMBER`` or
``COLLABORATOR``) or the workflow's own bot, so a marker pasted by anyone else is never
rewritten. Its ``**Status:**`` line holds the status, the evidence and the last run in one
line (``status_line``); a run replaces that line and nothing else in the comment
(``with_status``), and adds no comment once one exists. A second run on the same day and
commit writes nothing; each new day rewrites the line with the new run date.

Only items with a condition marker (``backlog_items.marker_key``) that pass the label check
(``label``, as ``plan_filing`` applies it) are read; an item without the marker is never
touched. No write edits an item's title, body, labels or assignees, so a person's edits stay.
A proposal declined before (``lib/run/decline_markers.py``, #813) is never written: its line
names the decline instead. ``plan_scheduled`` returns ``{mode, writes, notes, summary}``,
each write one of ``WRITE_OPS``; ``scripts/backlog_reconcile_apply.py`` runs them in the
workflow's one writer job. Pure stdlib; never touches the tracker.
Tests: ``tests/test_backlog_schedule.py``.
"""
from __future__ import annotations

import re
from collections.abc import Mapping, Sequence
from typing import NotRequired, TypedDict

from lib.assess_config import BACKLOG_MODES, DEFAULT_BACKLOG_WIP
from lib.report.backlog_items import DEFAULT_LABEL, condition_marker, item_labels, marker_key
from lib.report.backlog_reconcile import Proposal, ReconcileResult, RunFacts
from lib.report.backlog_wip import next_unlock_conditions, open_backlog

STATUS_MARKER = "<!-- assess:status -->"
STATUS_PREFIX = "**Status:**"
TRUSTED_ASSOCIATIONS = frozenset({"OWNER", "MEMBER", "COLLABORATOR"})
BOT_LOGINS = frozenset({"github-actions", "github-actions[bot]", "app/github-actions"})
FOOTER = "Generated by /assess - https://github.com/bjcoombs/ai-native-toolkit"
# The writes each mode allows; the writer refuses any other.
WRITE_OPS: dict[str, tuple[str, ...]] = {
    "propose": ("edit_comment",),
    "file": ("edit_comment", "add_comment", "create"),
    "file-and-close": ("edit_comment", "add_comment", "create", "close"),
}
_COMMENT_ID = re.compile(r"#issuecomment-(\d+)$")
_PROPOSED = {"close": "Proposed close", "reopen": "Proposed reopen", "demote": "Proposed demote to informational",
             "supersede": "Proposed close as superseded"}


class StatusComment(TypedDict):
    id: int
    body: str


class ScheduledWrite(TypedDict):
    """One tracker write: ``edit_comment``, ``add_comment``, ``close`` or ``create``."""

    op: str
    number: NotRequired[int]
    comment_id: NotRequired[int]
    body: NotRequired[str]
    title: NotRequired[str]
    labels: NotRequired[list[str]]
    status: NotRequired[str]  # create: the new item's status comment


class ScheduledPlan(TypedDict):
    mode: str
    writes: list[ScheduledWrite]
    notes: list[str]
    summary: str


def scheduled_facts(facts: RunFacts) -> RunFacts:
    """``facts`` read as a run the reconcile may propose on: the scheduled workflow is the opt-in."""
    out: RunFacts = {**facts, "interactive": True}
    return out


def _login(comment: Mapping[str, object]) -> str:
    who = comment.get("author") or comment.get("user")
    login = who.get("login") if isinstance(who, Mapping) else None
    return login if isinstance(login, str) else ""


def comment_id(comment: Mapping[str, object]) -> int | None:
    """The REST id of a comment: ``id`` when numeric (REST), else the ``#issuecomment-<id>`` in ``url`` (``gh --json``)."""
    raw = comment.get("id")
    if isinstance(raw, int) and not isinstance(raw, bool):
        return raw
    m = _COMMENT_ID.search(str(comment.get("url") or ""))
    return int(m.group(1)) if m else None


def status_comment(item: Mapping[str, object]) -> StatusComment | None:
    """The item's status comment: the first trusted comment holding ``STATUS_MARKER``, or None."""
    comments = item.get("comments")
    for c in comments if isinstance(comments, list) else []:
        if not isinstance(c, Mapping) or STATUS_MARKER not in str(c.get("body") or ""):
            continue
        association = c.get("authorAssociation") or c.get("author_association")
        if association not in TRUSTED_ASSOCIATIONS and _login(c) not in BOT_LOGINS:
            continue
        cid = comment_id(c)
        if cid is not None:
            return StatusComment(id=cid, body=str(c.get("body")))
    return None


def status_line(text: str, today: str, sha: str | None) -> str:
    """The one ``**Status:**`` line: the status and evidence, then the run date and commit."""
    commit = f", commit `{sha[:12]}`" if sha else ""
    return f"{STATUS_PREFIX} {text} Last run: {today}{commit}."


def with_status(body: str, line: str) -> str:
    """``body`` with its first ``**Status:**`` line replaced by ``line`` (added under the marker when it has none)."""
    lines = body.split("\n")
    for i, old in enumerate(lines):
        if old.startswith(STATUS_PREFIX):
            lines[i] = line + ("\r" if old.endswith("\r") else "")
            return "\n".join(lines)
    for i, old in enumerate(lines):
        if STATUS_MARKER in old:
            lines.insert(i + 1, line + ("\r" if old.endswith("\r") else ""))
            return "\n".join(lines)
    return body


def new_status_comment(line: str) -> str:
    """A new status comment holding ``line``."""
    return (f"{STATUS_MARKER}\n{line}\n\n_/assess keeps the status line above current on each scheduled "
            "run. It edits that line only and adds no other comment._\n")


def _reading(cid: str, facts: RunFacts) -> str:
    conditions = facts["conditions"]
    if conditions is None:
        return "This run has no level result, so the condition was not read."
    condition = conditions.get(cid)
    if condition is None:
        return f"This run's maturity model does not list `{cid}`."
    grade = condition.get("grade")
    return f"`{cid}` reads {condition.get('state')}" + (f" ({grade})." if isinstance(grade, str) else ".")


def _text(kind: str, reason: str, close: bool) -> str:
    if kind == "close" and close:
        return f"Closed by the scheduled reconcile: {reason}."
    return f"{_PROPOSED[kind]}: {reason}. Confirm it on the next interactive /assess run."


def _new_item(cid: str, step: object, facts: RunFacts, today: str, label: str) -> ScheduledWrite:
    condition = (facts["conditions"] or {}).get(cid, {})
    why = condition.get("why")
    step_name = f"Step {step}" if isinstance(step, int) else "the next Step"
    body = (f"**Condition:** `{cid}`, a gate of {step_name}.\n\n"
            + (f"{why.strip()}\n\n" if isinstance(why, str) and why.strip() else "")
            + "Filed by the scheduled /assess reconcile (`[backlog] mode` in `.assess/config.toml`). "
            "It closes the item only in `file-and-close` mode, once the condition holds.\n\n"
            f"---\n{FOOTER}\n\n{condition_marker(cid, facts['model'])}\n")
    line = status_line(_reading(cid, facts), today, facts["head_sha"])
    return ScheduledWrite(op="create", title=f"Meet {cid} to reach {step_name}", body=body,
                          labels=[label] if label else [], status=new_status_comment(line))


def _number(item: Mapping[str, object]) -> int | None:
    n = item.get("number")
    return n if isinstance(n, int) and not isinstance(n, bool) else None


def plan_scheduled(existing: Sequence[Mapping[str, object]], facts: RunFacts, result: ReconcileResult, *,
                   mode: str, today: str, declined: Mapping[int, str] | None = None,
                   label: str = DEFAULT_LABEL, wip: int = DEFAULT_BACKLOG_WIP,
                   level: object = None) -> ScheduledPlan:
    """The writes one scheduled run makes under ``mode``, from ``reconcile``'s ``result``.

    ``result`` holds the proposals left after the declined ones were held back; ``declined``
    maps a held-back item number to its disclosure line. ``existing`` items carry their
    ``comments`` (``gh issue list --json ...,comments``); ``level`` is ``run-context.json``
    ``level``, read for the next Step's gates in ``file`` modes.
    """
    if mode not in BACKLOG_MODES:
        raise ValueError(f"unknown backlog mode {mode!r}")
    declined = declined or {}
    close = mode == "file-and-close"
    proposals: dict[int, Proposal] = {p["number"]: p for p in result["proposals"]}
    rules = {r["number"]: r["line"] for r in result["rules_changed"]}
    writes: list[ScheduledWrite] = []
    missing = closed = 0
    for item in existing:
        number, key = _number(item), marker_key(str(item.get("body") or ""))
        if number is None or key is None or (label and label not in item_labels(item)):
            continue
        p = proposals.get(number)
        if p is not None:
            text = _text(p["kind"], p["reason"], close)
        elif number in declined:
            text = f"Declined before: {declined[number]}."
        elif number in rules:
            text = f"No change: {rules[number]}."
        else:
            text = _reading(f"{key[0]}.{key[1]}", facts)
        line = status_line(text, today, facts["head_sha"])
        comment = status_comment(item)
        if comment is not None:
            body = with_status(comment["body"], line)
            if body != comment["body"]:
                writes.append(ScheduledWrite(op="edit_comment", number=number, comment_id=comment["id"], body=body))
        elif mode == "propose":
            missing += 1
        else:
            writes.append(ScheduledWrite(op="add_comment", number=number, body=new_status_comment(line)))
        if p is not None and p["kind"] == "close" and close:
            writes.append(ScheduledWrite(op="close", number=number))
            closed += 1
    notes: list[str] = []
    if missing:
        notes.append(f"{missing} marked item(s) have no status comment; `propose` mode edits only an existing one")
    if mode != "propose":
        writes += _filings(existing, facts, today, label, wip, closed, level, notes)
    return ScheduledPlan(mode=mode, writes=writes, notes=notes, summary=_summary(mode, writes, notes))


def _filings(existing: Sequence[Mapping[str, object]], facts: RunFacts, today: str, label: str, wip: int,
             closed: int, level: object, notes: list[str]) -> list[ScheduledWrite]:
    """One new item per next-Step gate no item is marked for, while the open-item limit leaves a slot."""
    if facts["conditions"] is None:
        return []
    marked = {f"{k[0]}.{k[1]}" for i in existing if (k := marker_key(str(i.get("body") or ""))) is not None}
    nxt = level.get("next_step") if isinstance(level, Mapping) else None
    step = nxt.get("step") if isinstance(nxt, Mapping) else None
    wanted = [cid for cid in sorted(next_unlock_conditions(level)) if cid not in marked and condition_marker(cid, None)]
    free = max(0, wip - (len(open_backlog(existing, label)) - closed))
    if len(wanted) > free:
        notes.append(f"{len(wanted) - free} next-Step gate(s) not filed: the backlog holds at most {wip} open "
                     "item(s), the `[backlog] wip` limit")
    return [_new_item(cid, step, facts, today, label) for cid in wanted[:free]]


_VERB = {"edit_comment": "status line(s) updated", "add_comment": "status comment(s) added",
         "close": "item(s) closed", "create": "item(s) filed"}


def _summary(mode: str, writes: Sequence[ScheduledWrite], notes: Sequence[str]) -> str:
    counts = {op: sum(1 for w in writes if w["op"] == op) for op in _VERB}
    lines = [f"**Scheduled backlog reconcile** (`[backlog] mode = \"{mode}\"`): {len(writes)} write(s).", ""]
    lines += [f"- {counts[op]} {verb}" for op, verb in _VERB.items() if counts[op]]
    if notes:
        lines += [""] + [f"_{n}._" for n in notes]
    return "\n".join(lines).rstrip() + "\n"
