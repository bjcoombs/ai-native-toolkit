SCAN_FIELDS = {"name", "title", "summary", "collector", "reads", "network", "platform", "headless",
               "privacy", "used_by", "unknown_reasons", "evidence", "grades", "why", "why_source"}


def _manifest_data() -> dict[str, Any]:
    data: dict[str, Any] = cm.read_manifest()
    return data


@pytest.mark.parametrize("path", sorted(gen_catalog.outputs()), ids=lambda p: p.name)
def test_committed_catalog_is_current(path: Path) -> None:
    expected = gen_catalog.outputs()[path]
    assert path.is_file(), f"{path.name} is missing: run `make catalog` from the repository root"
    # Byte for byte: .gitattributes keeps both files LF in every checkout.
    assert path.read_bytes() == expected.encode("utf-8"), (
        f"{path.relative_to(gen_catalog.ROOT).as_posix()} is stale: run `make catalog` from the "
        "repository root (or `uv run --locked python scripts/gen_catalog.py` from skills/assess)")


def test_signal_order_follows_the_model_not_the_manifest() -> None:
    """Fragments group signals by collector (#982); the catalog lists them in model order."""
    data = _manifest_data()
    shuffled = copy.deepcopy(data)
    shuffled["entries"].reverse()
    collectors = [e for e in shuffled["entries"] if e["kind"] == "collector"]
    shuffled["entries"] = collectors[::-1] + [e for e in shuffled["entries"] if e["kind"] != "collector"]
    assert render_json(build_catalog(cm.parse_manifest(data))) \
        == render_json(build_catalog(cm.parse_manifest(shuffled)))


def test_a_manifest_title_change_changes_both_outputs() -> None:
    data = _manifest_data()
    edited = copy.deepcopy(data)
    entry = next(e for e in edited["entries"] if e["id"] == "core.ci_checks")
    entry["title"] = "A changed title"
    before, after = build_catalog(cm.parse_manifest(data)), build_catalog(cm.parse_manifest(edited))
    assert render_json(before) != render_json(after)
    assert render_markdown(before) != render_markdown(after)
    assert "A changed title" in render_markdown(after)


def test_generation_is_deterministic() -> None:
    first, second = gen_catalog.outputs(), gen_catalog.outputs()
    assert first == second
    for text in first.values():
        assert text.endswith("\n") and not text.endswith("\n\n")
        assert str(gen_catalog.ROOT) not in text


