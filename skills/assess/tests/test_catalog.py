"""The measures catalog is current, complete and deterministic (#794).

``docs/what-we-measure.md`` and ``references/measures.json`` are generated by
``scripts/gen_catalog.py`` from the check manifest, the default maturity model and the
signal input classes. ``test_committed_catalog_is_current`` is the staleness test: it
fails when either committed copy differs from what the generator writes, so a change to
``checks/core.toml``, ``levels/default.toml`` or ``lib/level_signals.py`` without
``make catalog`` fails here.
"""
from __future__ import annotations

import copy
import json
import re
from pathlib import Path
from typing import Any

import gen_catalog
import pytest

from lib import check_manifest as cm
from lib.catalog import (CATALOG_VERSION, GRADE_ORDER, UNCLASSIFIED, build_catalog, counts, criterion_text,
                         grade_of, render_json)
from lib.catalog_md import render_markdown
from lib.keyhole_signals import FINDING_ORDER
from lib.level_signals import SIGNAL_INPUTS, counts_toward_level, load_default_levels
from lib.scan_registry import SCANS
from lib.signals import known_scans

SCAN_FIELDS = {"name", "title", "summary", "collector", "reads", "network", "platform", "headless",
               "privacy", "used_by", "unknown_reasons", "evidence", "grades"}


def _manifest_data() -> dict[str, Any]:
    data: dict[str, Any] = cm.read_manifest()
    return data


@pytest.mark.parametrize("path", sorted(gen_catalog.outputs()), ids=lambda p: p.name)
def test_committed_catalog_is_current(path: Path) -> None:
    expected = gen_catalog.outputs()[path]
    assert path.is_file(), f"{path.name} is missing: run `make catalog` from the repository root"
    # Byte for byte: .gitattributes keeps both files LF in every checkout.
    assert path.read_bytes() == expected.encode("utf-8"), (
        f"{path.relative_to(gen_catalog.ROOT).as_posix()} is stale: run `make catalog` from the "
        "repository root (or `uv run --locked python scripts/gen_catalog.py` from skills/assess)")


def test_signal_order_follows_the_model_not_the_manifest() -> None:
    """Fragments group signals by collector (#982); the catalog lists them in model order."""
    data = _manifest_data()
    shuffled = copy.deepcopy(data)
    shuffled["entries"].reverse()
    collectors = [e for e in shuffled["entries"] if e["kind"] == "collector"]
    shuffled["entries"] = collectors[::-1] + [e for e in shuffled["entries"] if e["kind"] != "collector"]
    assert render_json(build_catalog(cm.parse_manifest(data))) \
        == render_json(build_catalog(cm.parse_manifest(shuffled)))


def test_a_manifest_title_change_changes_both_outputs() -> None:
    data = _manifest_data()
    edited = copy.deepcopy(data)
    entry = next(e for e in edited["entries"] if e["id"] == "core.ci_checks")
    entry["title"] = "A changed title"
    before, after = build_catalog(cm.parse_manifest(data)), build_catalog(cm.parse_manifest(edited))
    assert render_json(before) != render_json(after)
    assert render_markdown(before) != render_markdown(after)
    assert "A changed title" in render_markdown(after)


def test_generation_is_deterministic() -> None:
    first, second = gen_catalog.outputs(), gen_catalog.outputs()
    assert first == second
    for text in first.values():
        assert text.endswith("\n") and not text.endswith("\n\n")
        assert str(gen_catalog.ROOT) not in text


def test_every_known_scan_has_a_complete_entry() -> None:
    catalog = build_catalog()
    assert [s["name"] for s in catalog["scans"]] == known_scans()
    for scan in catalog["scans"]:
        assert set(scan) == SCAN_FIELDS, scan["name"]
        assert scan["grades"], scan["name"]
        assert set(scan["privacy"]) == {"written", "strings_kept"}


def test_every_registry_scan_row_criterion_and_finding_is_listed() -> None:
    catalog = build_catalog()
    assert [c["name"] for c in catalog["collectors"]] == [spec.key for spec in SCANS]
    model = load_default_levels()
    assert [(r["id"], [lv["level"] for lv in r["levels"]]) for r in catalog["rows"]] == \
        [(r["id"], [lv["level"] for lv in r["levels"]]) for r in model["rows"]]
    listed = [(c["signal"], c["op"], c["value"]) for r in catalog["rows"]
              for lv in r["levels"] for c in lv["criteria"]]
    assert listed == [(c["signal"], c["op"], c["value"]) for r in model["rows"]
                      for lv in r["levels"] for c in lv["criteria"]]
    assert [f["name"] for f in catalog["findings"]] == list(FINDING_ORDER)


def test_grades_and_counting() -> None:
    catalog = build_catalog()
    assert catalog["catalog_version"] == CATALOG_VERSION
    assert {g["grade"]: g["counts"] for g in catalog["grades"]} == {
        "config_only": False, "declared": False, "measured": True, "verified": True}
    assert not counts(UNCLASSIFIED)
    assert [counts_toward_level(g) for g in ("config_only", "declared", "measured", "verified", "x")] \
        == [False, False, True, True, False]
    signals = {s["path"]: s for s in catalog["signals"]}
    crits = [c for r in catalog["rows"] for lv in r["levels"] for c in lv["criteria"]]
    assert crits
    for c in crits:
        assert c["key"] == f"{c['key'].split(':', 1)[0]}:{c['signal']}"
        assert c["input_class"] == SIGNAL_INPUTS[c["signal"]]
        assert c["grade"] == grade_of(c["input_class"]) and c["counts"] is counts(c["grade"])
        assert c["text"].startswith(f"{signals[c['signal']]['title']}: ")
    assert any(c["counts"] for c in crits) and any(not c["counts"] for c in crits)


def test_scan_entries_carry_relations_reasons_and_privacy() -> None:
    scans = {s["name"]: s for s in build_catalog()["scans"]}
    ci = scans["ci_checks"]
    model = load_default_levels()
    assert ci["used_by"]["rows"] == sorted({r["id"] for r in model["rows"] for lv in r["levels"]
                                            for c in lv["criteria"] if c["signal"].startswith("ci_checks.")})
    assert any(r.startswith("layer-5-") for r in ci["used_by"]["rows"])
    declared = next(c for c in cm.collectors(cm.load_manifest()) if c["id"] == "core.ci_checks")
    assert [r["code"] for r in ci["unknown_reasons"]] == [r["code"] for r in declared["unknown_reasons"]]
    assert "included_jobs" in [r["code"] for r in ci["unknown_reasons"]]
    assert ci["privacy"]["strings_kept"]["ci_checks.basis"] == "token"
    assert [r["code"] for r in scans["behaviour"]["unknown_reasons"]][0] == "not_registered"
    assert "hidden_coupling" in scans["behaviour"]["used_by"]["findings"]
    assert scans["review_reality"]["unknown_reasons"][0]["code"] == "network"
    assert "--platform" in scans["review_reality"]["unknown_reasons"][0]["next_step"]
    assert scans["config_drift"]["unknown_reasons"][0]["next_step"].startswith("Run /assess")
    assert scans["delivery"]["headless"] == "platform_only"
    # A spread collector's block keeps only its own privacy patterns.
    assert all(k.startswith("structure") for k in scans["structure"]["privacy"]["strings_kept"])
    assert scans["agent_harness"]["grades"] == [UNCLASSIFIED]
    pm = {grade_of(c) for s, c in SIGNAL_INPUTS.items() if s.startswith("promissory_markers.")}
    assert scans["promissory_markers"]["grades"] == [g for g in GRADE_ORDER if g in pm]


def test_criterion_text_words() -> None:
    assert criterion_text({"signal": "a.b", "op": "in", "value": ["x", "y"]}, "T") == "T: is one of x, y"
    assert criterion_text({"signal": "a.b", "op": "ne", "value": False}, "T") == "T: is not false"


def test_a_criterion_without_manifest_entries_still_renders() -> None:
    model = load_default_levels()
    model["rows"][0]["levels"][0]["criteria"] = [{"signal": "ci_checks.ci_files", "op": "gt", "value": 0}]
    row = build_catalog(model=model)["rows"][0]
    crit = row["levels"][0]["criteria"][0]
    assert (crit["grade"], crit["counts"], crit["fix"]) == (UNCLASSIFIED, False, "")
    assert crit["title"] == "ci_checks.ci_files"


def test_every_source_exists() -> None:
    for source in build_catalog()["sources"]:
        assert (gen_catalog.ROOT / source).is_file(), source


def test_a_pipe_in_a_criterion_value_keeps_the_table_columns() -> None:
    model = load_default_levels()
    model["rows"][0]["levels"][0]["criteria"] = [{"signal": "x.y", "op": "in", "value": ["a|b"]}]
    row_lines = [line for line in render_markdown(build_catalog(model=model)).splitlines()
                 if "x.y in" in line]
    assert len(row_lines) == 1
    assert len(re.findall(r"(?<!\\)\|", row_lines[0])) == 7  # six columns


def test_markdown_avoids_the_retired_vocabulary() -> None:
    text = render_markdown(build_catalog())
    assert not re.search(r"\bLevel \d", text)
    for word in ("rubric", "Not Ready", "AI-Native", "Basic", "Solid"):
        assert word not in text
    assert "](../skills/assess/references/measures.json)" in text
    assert (gen_catalog.ROOT / "skills" / "assess" / "references" / "measures.json").is_file()


def test_gen_catalog_writes_and_checks(tmp_path: Path, monkeypatch: pytest.MonkeyPatch,
                                       capsys: pytest.CaptureFixture[str]) -> None:
    md, js = tmp_path / "docs" / "what-we-measure.md", tmp_path / "measures.json"
    md.parent.mkdir()
    monkeypatch.setattr(gen_catalog, "ROOT", tmp_path)
    monkeypatch.setattr(gen_catalog, "MARKDOWN", md)
    monkeypatch.setattr(gen_catalog, "JSON", js)
    assert gen_catalog.main(["--check"]) == 1
    assert "stale: docs/what-we-measure.md" in capsys.readouterr().err
    assert gen_catalog.main([]) == 0
    assert json.loads(js.read_text(encoding="utf-8"))["catalog_version"] == CATALOG_VERSION
    assert b"\r\n" not in md.read_bytes()
    assert gen_catalog.main(["--check"]) == 0
