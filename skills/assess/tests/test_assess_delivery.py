"""Text contract for how /assess delivers its findings (issues #591 and #592).

#591: on a read-only target that takes contributions, the first upstream offer is
issues linking the fork-hosted report; the snapshot PR is a secondary opt-in.
#592: filed items are single-concern, "Done when" leads with repository-native
checks, and the report never narrates a scorer-draft correction.
"""
from __future__ import annotations

import re
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[3]
PR_SKILL = REPO_ROOT / "skills" / "assess-pr" / "SKILL.md"
FINDINGS_SKILL = REPO_ROOT / "skills" / "assess-findings" / "SKILL.md"
GOLDEN_REPORT = Path(__file__).resolve().parent / "fixtures" / "golden" / "assess-report-baseline.md"

TOOLKIT_INTERNALS = re.compile(r"/assess|run-context|layer\d|\w+\.\w+_\w+|`[a-z]+_[a-z_]+`")


def _issue_body_template() -> str:
    text = PR_SKILL.read_text(encoding="utf-8")
    after = text.split("Example minimal body shape", 1)[1]
    block = re.search(r"^```markdown\n(.*?)^```$", after, flags=re.M | re.S)
    assert block, "no markdown fence after the issue body shape heading"
    return block.group(1)


def _read_only_bullet() -> str:
    text = PR_SKILL.read_text(encoding="utf-8")
    return next(
        line for line in text.splitlines()
        if line.startswith("- `CAN_PUSH=0`") and "`NO_CONTRIBUTIONS=0`" in line
    )


def test_read_only_offer_leads_with_upstream_issues():
    bullet = _read_only_bullet()
    issues_at = bullet.index("upstream-issues flow")
    pr_at = bullet.index("fork-based PR flow")
    assert issues_at < pr_at
    assert "opt-in" in bullet
    assert "no `.assess/` file for upstream" in bullet


def test_upstream_issues_flow_hosts_report_in_fork_without_a_pr():
    text = PR_SKILL.read_text(encoding="utf-8")
    flow = text.split("selected the upstream-issues offer", 1)[1].split("If the user **selected the PR offer**", 1)[0]
    assert "REPORT_URL" in flow
    assert "open no PR" in flow
    assert "$GH_SLUG" in flow


def test_issue_body_has_a_repo_native_done_when_first():
    body = _issue_body_template()
    done = body.split("### Done when", 1)[1].split("###", 1)[0]
    criteria = [line for line in done.splitlines() if line.startswith("- ")]
    assert len(criteria) >= 2
    assert not TOOLKIT_INTERNALS.search(criteria[0]), criteria[0]
    assert criteria[-1].startswith("- Optional:")


def test_issue_body_leads_with_findings_not_the_footer():
    body = _issue_body_template()
    first = next(line for line in body.splitlines() if line.strip())
    assert "Generated by" not in first and "plugin" not in first
    assert body.rstrip().splitlines()[-1].startswith("Generated by /assess")


def test_compound_actions_are_split_before_filing():
    pr_text = PR_SKILL.read_text(encoding="utf-8")
    assert "**One concern per item.**" in pr_text
    findings = FINDINGS_SKILL.read_text(encoding="utf-8")
    assert "**One concern per action.**" in findings
    assert "combine a prescribed path with a related gap" not in findings


def test_findings_never_narrate_a_score_correction():
    findings = FINDINGS_SKILL.read_text(encoding="utf-8")
    assert "**State the final score only.**" in findings
    assert "scorer's draft" not in GOLDEN_REPORT.read_text(encoding="utf-8")
